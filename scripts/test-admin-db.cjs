const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require(path.join(process.env.TEMP,'hq-admin-db-check/node_modules/@electric-sql/pglite'));
(async()=>{
 const db=new PGlite();
 const staff='00000000-0000-0000-0000-000000000001';
 const member='00000000-0000-0000-0000-000000000002';
 await db.exec(`create role anon;create role authenticated;create schema auth;
 create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}',created_at timestamptz default now());
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema auth to anon,authenticated;
 alter default privileges in schema public grant all on tables to anon,authenticated;
 insert into auth.users(id,email) values('${staff}','staff@example.invalid'),('${member}','member@example.invalid');`);
 await db.exec(fs.readFileSync('supabase/migrations/20261013_admin.sql','utf8'));
 await db.query('insert into public.hq_staff(user_id) values($1)',[staff]);
 const resource=(await db.query("select id from hq_resources where name='Standard Station'")).rows[0].id;
 const plan=(await db.query("select id from hq_plans where name='Flex Membership'")).rows[0].id;
 await db.query('update hq_resources set capacity=1 where id=$1',[resource]);
 async function asUser(id){await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated');}
 await asUser(member);
 assert.equal((await db.query('select hq_is_admin() as allowed')).rows[0].allowed,false);
 assert.equal((await db.query('select * from hq_resources')).rows.length,0);
 await assert.rejects(db.query('insert into hq_staff(user_id) values($1)',[member]),/permission denied/);
 await assert.rejects(db.query("select hq_create_reservation($1,$2,now()+interval '48 hours',now()+interval '50 hours')",[member,resource]),/Staff access required/);
 await assert.rejects(db.query('select * from hq_list_members()'),/Staff access required/);
 await asUser(staff);
 assert.equal((await db.query('select hq_is_admin() as allowed')).rows[0].allowed,true);
 assert.equal((await db.query('select * from hq_list_members()')).rows.length,2);
 const booking=(await db.query("select hq_create_reservation($1,$2,now()+interval '48 hours',now()+interval '50 hours') as id",[member,resource])).rows[0].id;
 await assert.rejects(db.query("select hq_create_reservation($1,$2,now()+interval '49 hours',now()+interval '51 hours')",[member,resource]),/fully booked/);
 await assert.rejects(db.query("select hq_reservation_action($1,'check-in')",[booking]),/active reserved time slot/);
 await assert.rejects(db.query("update hq_reservations set status='completed' where id=$1",[booking]),/permission denied/);
 await db.query("select hq_reservation_action($1,'cancel')",[booking]);
 assert.equal((await db.query('select * from hq_refunds')).rows.length,0,'no refund for uncollected quote');
 const paid=(await db.query("select hq_create_reservation($1,$2,now()+interval '48 hours',now()+interval '50 hours') as id",[member,resource])).rows[0].id;
 await db.exec('reset role');
 await db.query("insert into hq_payments(user_id,reservation_id,amount,status) values($1,$2,40,'paid')",[member,paid]);
 await asUser(staff);
 await db.query("select hq_reservation_action($1,'cancel')",[paid]);
 const refund=(await db.query('select * from hq_refunds')).rows[0];
 assert.equal(Number(refund.amount),40,'refund cannot exceed collected payment');
 await db.query("select hq_review_refund($1,'approved')",[refund.id]);
 await assert.rejects(db.query("select hq_review_refund($1,'rejected')",[refund.id]),/already reviewed/);
 assert.equal((await db.query('select status from hq_payments')).rows[0].status,'paid','review does not fake a provider refund');
 await db.query('select hq_grant_membership($1,$2)',[member,plan]);
 await db.query('select hq_grant_membership($1,$2)',[member,plan]);
 assert.equal((await db.query('select remaining_hours from hq_memberships')).rows[0].remaining_hours,120);
 assert.ok((await db.query('select * from hq_audit')).rows.length>0);
 const visit=(await db.query("select hq_create_reservation($1,$2,now()+interval '60 hours',now()+interval '61 hours') as id",[member,resource])).rows[0].id;
 // Simulate clock progression as the database owner in the isolated test only.
 await db.exec('reset role');
 await db.query("update hq_reservations set starts_at=now()-interval '1 hour',ends_at=now()+interval '1 hour' where id=$1",[visit]);
 await asUser(staff);
 await db.query("select hq_reservation_action($1,'check-in')",[visit]);
 await db.exec('reset role');
 await db.query("update hq_reservations set starts_at=now()-interval '2 hours',ends_at=now()-interval '30 minutes' where id=$1",[visit]);
 await asUser(staff);
 await db.query("select hq_reservation_action($1,'check-out')",[visit]);
 assert.equal(Number((await db.query('select overtime_due from hq_reservations where id=$1',[visit])).rows[0].overtime_due),35,'half-hour overtime rounds to one snapshotted-rate hour');
 await assert.rejects(db.query("select hq_reservation_action($1,'check-out')",[visit]),/not checked in/);
 await asUser(member);
 assert.equal((await db.query('select * from hq_reservations')).rows.length,3,'member can read own server reservations');
 await db.close();
 console.log('Migration applied to isolated PostgreSQL. Staff-access, RLS, capacity, refund, renewal, overtime, and audit checks passed.');
})().catch(e=>{console.error(e.message);process.exitCode=1;});

