const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
let result;
let last;
const fakeAuth = Object.fromEntries(['signInWithPassword','signUp','signOut'].map(name => [name, async input => { last = { name, input }; return result; }]));
const sandbox = { exports: {}, require: name => { assert.equal(name,'./supabase'); return { requireSupabase: () => ({auth:fakeAuth}) }; } };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/auth-api.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,sandbox);
const api = sandbox.exports;
(async () => {
  result = { data:{session:{user:{id:'member-1'}}},error:null };
  assert.equal((await api.signIn(' MEMBER@EXAMPLE.COM ','test-password')).user.id,'member-1');
  assert.equal(last.input.email,'member@example.com');
  assert.equal(last.input.password,'test-password');
  result={data:{session:null},error:new Error('Invalid login credentials')};
  await assert.rejects(api.signIn('member@example.com','wrong'),/Invalid login credentials/);
  result={data:{session:null},error:null};
  await assert.rejects(api.signIn('member@example.com','test-password'),/did not return a session/);
  result={data:{session:null,user:{id:'new-member'}},error:null};
  assert.equal((await api.registerMember({email:' NEW@EXAMPLE.COM ',password:'test-password',fullName:' New Member ',mobileNumber:' 09123456789 '})).session,null);
  assert.equal(last.input.email,'new@example.com');
  assert.equal(last.input.options.data.full_name,'New Member');
  assert.equal(last.input.options.data.mobile_number,'09123456789');
  assert.equal(last.input.options.data.role,undefined);
  result={data:{},error:new Error('Registration disabled')};
  await assert.rejects(api.registerMember({email:'a@b.com',password:'test-password',fullName:'Test',mobileNumber:'09123456789'}),/Registration disabled/);
  result={error:null}; await api.signOut();
  assert.equal(last.input.scope,'local');
  result={error:new Error('Network error')};
  await assert.rejects(api.signOut(),/Network error/);
  console.log('13 authentication service checks passed. No remote accounts created.');
})().catch(error => { console.error(error); process.exitCode=1; });
