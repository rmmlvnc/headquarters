const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/features/catalog.ts', 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const sandbox = { exports: {}, require: () => 1 };
vm.runInNewContext(output, sandbox);
const { available, cancellationRefund, overtimeCharge } = sandbox.exports;
const h = 3600000;
const b = { id:'a', spaceId:'desk', addons:['laptop'], status:'reserved', start:10*h, end:12*h, total:100 };
assert.equal(available([b], 'desk', 1, 11*h, 13*h), 0, 'overlap consumes capacity');
assert.equal(available([b], 'desk', 1, 12*h, 13*h), 1, 'adjacent bookings do not overlap');
assert.equal(available([{...b,status:'cancelled'}], 'desk', 1, 11*h,13*h), 1, 'cancellation releases capacity');
assert.equal(available([b], 'laptop', 1,11*h,13*h),0,'equipment is reserved');
assert.equal(available([b,{...b,id:'b',start:12*h,end:14*h}], 'desk',2,10*h,14*h),1,'peak concurrency avoids false capacity rejection');
assert.equal(available([b], 'desk',1,11*h,13*h,'a'),1,'excluded reservation is not counted');
assert.equal(cancellationRefund({...b,start:30*h},6*h),100,'24-hour cancellation gets full estimate');
assert.equal(cancellationRefund({...b,start:30*h},6*h+1),0,'late cancellation has zero estimate');
assert.equal(cancellationRefund({...b,status:'checked-in',start:30*h},0),0,'checked-in booking cannot be refunded');
assert.equal(overtimeCharge(b,12*h,35),0);
assert.equal(overtimeCharge(b,12*h+1,35),35,'partial extra hour rounds up');
assert.equal(overtimeCharge(b,13*h+1,35),70);
console.log('12 booking, equipment, refund, and overtime checks passed.');
